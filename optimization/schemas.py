"""Domain and mathematical schemas for the LifeLink Optimization Engine."""

from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class TriageCategory(str, Enum):
    RED = "RED"          # Immediate: Life-threatening, requires immediate care
    YELLOW = "YELLOW"    # Delayed: Serious, but can wait short duration
    GREEN = "GREEN"      # Minor: Walking wounded
    BLACK = "BLACK"      # Expectant / Deceased


class MedicalSpecialty(str, Enum):
    GENERAL_TRAUMA = "GENERAL_TRAUMA"
    NEUROSURGERY = "NEUROSURGERY"
    PEDIATRIC_TRAUMA = "PEDIATRIC_TRAUMA"
    BURN_CARE = "BURN_CARE"
    CARDIOTHORACIC = "CARDIOTHORACIC"
    ORTHOPEDIC = "ORTHOPEDIC"


class Patient(BaseModel):
    id: str
    latitude: float
    longitude: float
    triage_category: TriageCategory
    urgency_weight: float = Field(
        ..., ge=0.0, le=100.0,
        description="Priority penalty weight generated by Triage Agent (e.g. RED: 80-100)"
    )
    required_specialties: List[MedicalSpecialty] = Field(default_factory=list)
    stabilization_time_minutes: float = Field(
        default=5.0,
        description="Estimated paramedic on-scene stabilization time"
    )
    golden_hour_deadline_minutes: float = Field(
        default=60.0,
        description="Maximum safe time to surgery"
    )


class AmbulanceType(str, Enum):
    ALS = "ALS"  # Advanced Life Support
    BLS = "BLS"  # Basic Life Support


class Ambulance(BaseModel):
    id: str
    callsign: str
    latitude: float
    longitude: float
    ambulance_type: AmbulanceType = AmbulanceType.ALS
    capacity: int = Field(default=1, ge=1, le=4)
    is_available: bool = True
    current_assigned_patient_id: Optional[str] = None


class Hospital(BaseModel):
    id: str
    name: str
    latitude: float
    longitude: float
    icu_capacity: int = Field(..., ge=0, description="Available ICU / critical beds")
    operating_rooms_available: int = Field(..., ge=0)
    supported_specialties: List[MedicalSpecialty] = Field(default_factory=list)
    current_occupancy: int = 0


class DispatchAssignment(BaseModel):
    patient_id: str
    ambulance_id: str
    hospital_id: str
    ambulance_eta_minutes: float
    hospital_eta_minutes: float
    total_time_to_care_minutes: float
    urgency_score: float
    clinical_rationale: Optional[str] = None


class OptimizationSolution(BaseModel):
    status: str  # "OPTIMAL", "FEASIBLE", "INFEASIBLE"
    solve_time_ms: float
    objective_value: float
    assignments: List[DispatchAssignment]
    unassigned_patient_ids: List[str] = Field(default_factory=list)
    solver_metadata: Dict[str, str] = Field(default_factory=dict)
